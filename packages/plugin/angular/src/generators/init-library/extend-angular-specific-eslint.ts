import {
  ProjectConfiguration,
  Tree,
} from '@nx/devkit';
import {
  CoerceFile,
  IsRxapRepository,
} from '@rxap/workspace-utilities';
import { relative } from 'path';

export function extendAngularSpecificEslint(tree: Tree, project: ProjectConfiguration) {

  if (!IsRxapRepository(tree)) {
    return;
  }

  const projectRoot = project.root;

  const relativeToAngularRoot = relative(projectRoot, 'packages/angular');

  const importPath = relativeToAngularRoot + '/eslint.config.mjs';

  const eslintConfigFilePath = `${ projectRoot }/eslint.config.mjs`;
  const defaultEslintConfig = `import baseConfig from '${ importPath }';

export default [
  ...baseConfig,
];
`;

  if (!tree.exists(eslintConfigFilePath)) {
    CoerceFile(tree, eslintConfigFilePath, defaultEslintConfig);
    return;
  }

  // the config was generated by nx and does not extend the angular specific configuration
  if (!tree.read(eslintConfigFilePath)!.toString('utf-8').includes(importPath)) {
    CoerceFile(tree, eslintConfigFilePath, defaultEslintConfig, true);
  }

}
