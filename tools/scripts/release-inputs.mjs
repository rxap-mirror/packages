#!/usr/bin/env node
/**
 * Writes the `spec:inputs` header of .gitlab-ci.yml: the release choices of the Run pipeline form as dropdowns
 * (RELEASE_WORKFLOW.md "Releases in CI").
 *
 *   release              → NX_RELEASE         (nightly | stable | publish-only)
 *   release_specifier    → RELEASE_SPECIFIER  (prerelease, patch, minor, ...)
 *   release_projects_*   → RELEASE_PROJECTS   (multi-select per package family; the selections are joined)
 *
 * GitLab allows at most 50 options per input and 20 inputs per pipeline, so the packages are split into families
 * (angular is split again into chunks of at most 50). The option lists come from the "packages" release group, so
 * they must be regenerated whenever a package is added, renamed or removed — release-inputs.test.mjs fails until then.
 *
 * Usage: node tools/scripts/release-inputs.mjs            rewrite .gitlab-ci.yml
 *        node tools/scripts/release-inputs.mjs --check    exit 1 when .gitlab-ci.yml is out of date
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readGroupProjects } from './lib/release-plan.mjs';

export const MAX_OPTIONS = 50;
export const MAX_INPUTS = 20;

export const RELEASE_KINDS = [ 'nightly', 'stable', 'publish-only' ];
export const SPECIFIERS = [ 'prerelease', 'patch', 'minor', 'major', 'prepatch', 'preminor', 'premajor' ];

/** package family of a project root (packages/<folder>/...) */
export const FAMILIES = [
  { key: 'angular', title: 'Angular packages', folders: [ 'angular' ] },
  { key: 'nest', title: 'NestJS packages', folders: [ 'nest' ] },
  { key: 'tooling', title: 'Nx plugins, schematics, presets and workspace tools', folders: [ 'plugin', 'schematic', 'preset', 'workspace' ] },
  { key: 'other', title: 'all other packages (n8n, node, browser, utilities, ...)', folders: null },
];

const folderOf = root => root.split(/[\\/]/).filter(Boolean)[1];

/**
 * The project inputs: one per family, split into chunks of at most MAX_OPTIONS names.
 * @param projects [{ name, root }] of the "packages" release group
 * @returns [{ key, description, options }]
 */
export function buildProjectInputs(projects) {
  const named = new Set(FAMILIES.flatMap(f => f.folders ?? []));
  const inputs = [];
  for (const family of FAMILIES) {
    const names = projects
      .filter(p => family.folders ? family.folders.includes(folderOf(p.root)) : !named.has(folderOf(p.root)))
      .map(p => p.name)
      .sort();
    if (names.length === 0) {
      continue;
    }
    const chunks = Math.ceil(names.length / MAX_OPTIONS);
    const size = Math.ceil(names.length / chunks);
    for (let i = 0; i < chunks; i++) {
      const options = names.slice(i * size, (i + 1) * size);
      const range = chunks > 1 ? ` (${ options[0] } … ${ options.at(-1) })` : '';
      inputs.push({
        key: chunks > 1 ? `release_projects_${ family.key }_${ i + 1 }` : `release_projects_${ family.key }`,
        description: `Release: only these ${ family.title }${ range }. Leave every project list empty to release all changed packages.`,
        options,
      });
    }
  }
  if (inputs.length + 2 > MAX_INPUTS) {
    throw new Error(`${ inputs.length + 2 } inputs: GitLab allows at most ${ MAX_INPUTS } per pipeline`);
  }
  return inputs;
}

const q = s => `'${ s.replaceAll('\'', '\'\'') }'`;

/** the spec header (everything before the first `---` line of .gitlab-ci.yml) */
export function renderHeader(projectInputs) {
  const lines = [
    '# Generated by tools/scripts/release-inputs.mjs from the "packages" release group: do not edit by hand.',
    '# The Run pipeline form shows these inputs; they only set the release variables below (`variables:`).',
    'spec:',
    '  inputs:',
    '    release:',
    `      description: ${ q('Release to run: nightly (development, -dev prerelease), stable (latest, graduation), publish-only (pack and publish the newest release commit again). Empty: a normal pipeline.') }`,
    '      default: \'\'',
    `      options: [ '', ${ RELEASE_KINDS.map(q).join(', ') } ]`,
    '    release_specifier:',
    `      description: ${ q('Release: version bump instead of the conventional commits (e.g. prerelease bumps every selected package). Empty: from the commits.') }`,
    '      default: \'\'',
    `      options: [ '', ${ SPECIFIERS.map(q).join(', ') } ]`,
  ];
  for (const input of projectInputs) {
    lines.push(
      `    ${ input.key }:`,
      `      description: ${ q(input.description) }`,
      '      type: array',
      '      default: []',
      '      options:',
      ...input.options.map(o => `        - ${ o }`),
    );
  }
  lines.push('---');
  return lines.join('\n') + '\n';
}

/** the RELEASE_PROJECTS variable: the JSON arrays of all project inputs, release-ci.mjs parses the names out */
export const renderProjectsVariable = projectInputs =>
  `  RELEASE_PROJECTS: "${ projectInputs.map(i => `$[[ inputs.${ i.key } ]]`).join(' ') }"`;

/** content with the generated header and RELEASE_PROJECTS line */
export function apply(content, projectInputs) {
  const sep = content.match(/^---\n/m);
  const body = sep ? content.slice(sep.index + sep[0].length) : content;
  if (!/^ {2}RELEASE_PROJECTS: .*$/m.test(body)) {
    throw new Error('.gitlab-ci.yml has no `  RELEASE_PROJECTS: ` line in its top-level variables');
  }
  return renderHeader(projectInputs) + body.replace(/^ {2}RELEASE_PROJECTS: .*$/m, renderProjectsVariable(projectInputs));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = resolve(fileURLToPath(import.meta.url), '../../..');
  process.chdir(root); // project roots relative to the workspace: packages/<folder>/...
  const file = '.gitlab-ci.yml';
  const content = readFileSync(file, 'utf-8');
  const next = apply(content, buildProjectInputs(readGroupProjects('packages')));
  if (process.argv.includes('--check')) {
    if (next !== content) {
      console.error('.gitlab-ci.yml release inputs are out of date: run node tools/scripts/release-inputs.mjs');
      process.exit(1);
    }
    console.log('.gitlab-ci.yml release inputs are up to date');
  } else if (next !== content) {
    writeFileSync(file, next);
    console.log('.gitlab-ci.yml release inputs updated');
  } else {
    console.log('.gitlab-ci.yml release inputs are up to date');
  }
}
