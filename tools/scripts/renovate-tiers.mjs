#!/usr/bin/env node
/**
 * Generates renovate-tiers.json: the 7- and 14-day release cooldown tiers for Renovate.
 *
 * Renovate's `minimumReleaseAge` is one value per package rule, and renovate.json5 sets the strictest tier (30 days)
 * as the default. This script looks up the weekly npm downloads of every root dependency and lists the popular ones
 * in package rules (>= 1_000_000/week -> 7 days, >= 100_000 -> 14 days, else 30 days; unknown counts -> 30 days).
 * The 30-day rule repeats the default but records the classification, so `--missing-only` (used on Renovate
 * branches) only looks up dependencies that are not classified yet.
 * renovate.json5 extends the file (`local>` preset); tools/scripts/renovate-post-upgrade.mjs regenerates it on every
 * Renovate branch, run `pnpm renovate:tiers` after adding a dependency by hand.
 *
 * Usage: node tools/scripts/renovate-tiers.mjs [--missing-only] [--check]   (--check: exit 1 if the file is outdated)
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const OUTPUT = 'renovate-tiers.json';
export const TIERS = [
  { minWeekly: 1_000_000, days: 7 },
  { minWeekly: 100_000, days: 14 },
  { minWeekly: 0, days: 30 },
];
const CACHE_PATH = 'node_modules/.cache/dependency-cooldown-downloads.json';
const CACHE_TTL = 7 * 86_400_000;

/** cooldown days for a weekly download count (unknown -> strictest tier) */
export function tierDays(weekly) {
  return TIERS.find(t => (weekly ?? -1) >= t.minWeekly)?.days ?? TIERS.at(-1).days;
}

/** the root dependencies that Renovate may update (workspace packages are excluded) */
export function rootDependencies(pkg) {
  return [ ...new Set([ ...Object.keys(pkg.dependencies ?? {}), ...Object.keys(pkg.devDependencies ?? {}) ]) ]
    .filter(name => !name.startsWith('@rxap/'))
    .sort();
}

/** name -> days of an existing renovate-tiers.json */
export function classified(content) {
  const out = {};
  for (const rule of content?.packageRules ?? []) {
    const days = parseInt(rule.minimumReleaseAge, 10);
    for (const name of rule.matchPackageNames ?? []) {
      out[name] = days;
    }
  }
  return out;
}

/** a weekly count that falls into the tier `days` (to reuse an existing classification) */
export const weeklyForDays = days => TIERS.find(t => t.days === days)?.minWeekly ?? 0;

/** the renovate-tiers.json content for `downloads` (name -> weekly count or null) */
export function buildTiers(downloads) {
  const byDays = days => Object.keys(downloads).filter(n => tierDays(downloads[n]) === days).sort();
  return {
    $schema: 'https://docs.renovatebot.com/renovate-schema.json',
    description: [ 'GENERATED by tools/scripts/renovate-tiers.mjs - do not edit. Release cooldown tiers by weekly npm downloads; everything else stays on the 30-day default of renovate.json5.' ],
    packageRules: TIERS.map(({ minWeekly, days }) => ({
      description: `>= ${ minWeekly.toLocaleString('en') } weekly downloads: ${ days }-day cooldown`,
      matchDatasources: [ 'npm' ],
      matchPackageNames: byDays(days),
      minimumReleaseAge: `${ days } days`,
    })).filter(rule => rule.matchPackageNames.length > 0),
  };
}

export const serialize = content => `${ JSON.stringify(content, null, 2) }\n`;

function readCache() {
  try {
    return JSON.parse(readFileSync(CACHE_PATH, 'utf8'));
  } catch {
    return {};
  }
}

async function weeklyDownloads(name, cache) {
  if (cache[name] && Date.now() - cache[name].at < CACHE_TTL) {
    return cache[name].weekly;
  }
  for (let attempt = 0; attempt < 8; attempt++) {
    const res = await fetch(`https://api.npmjs.org/downloads/point/last-week/${ name.replace('/', '%2f') }`);
    if (res.status === 429) {
      await new Promise(r => setTimeout(r, (Number(res.headers.get('retry-after')) || 2 * (attempt + 1)) * 1000));
      continue;
    }
    if (!res.ok) {
      return null;
    }
    const weekly = (await res.json()).downloads ?? 0;
    cache[name] = { weekly, at: Date.now() };
    await new Promise(r => setTimeout(r, 150));
    return weekly;
  }
  return null;
}

async function main() {
  const pkg = JSON.parse(readFileSync('package.json', 'utf8'));
  const cache = readCache();
  const known = process.argv.includes('--missing-only') && existsSync(OUTPUT) ? classified(JSON.parse(readFileSync(OUTPUT, 'utf8'))) : {};
  const downloads = {};
  for (const name of rootDependencies(pkg)) {
    downloads[name] = name in known ? weeklyForDays(known[name]) : await weeklyDownloads(name, cache);
  }
  mkdirSync(dirname(CACHE_PATH), { recursive: true });
  writeFileSync(CACHE_PATH, JSON.stringify(cache));

  const next = serialize(buildTiers(downloads));
  const unknown = Object.keys(downloads).filter(n => downloads[n] === null);
  if (unknown.length) {
    console.log(`no download count for ${ unknown.join(', ') } (stay on 30 days)`);
  }
  if (process.argv.includes('--check')) {
    const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : '';
    console.log(current === next ? `${ OUTPUT } is up to date` : `${ OUTPUT } is outdated: run pnpm renovate:tiers`);
    process.exit(current === next ? 0 : 1);
  }
  writeFileSync(OUTPUT, next);
  const rules = buildTiers(downloads).packageRules;
  console.log(`wrote ${ OUTPUT }: ${ rules.map(r => `${ r.matchPackageNames.length } x ${ r.minimumReleaseAge }`).join(', ') }`);
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  await main();
}
